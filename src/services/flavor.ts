/** 이름+날짜로 정해지는 오늘의 운세 — 하루 동안 같은 결과가 나온다 */
export const getFortune = (name: string, day: string): Fortune => {
    const seed = hashSeed(`${name.trim().toLowerCase()}::${day}`);
    const totalWeight = GRADES.reduce((s, g) => s + g.weight, 0);
    let cursor = roll(seed, 1) * totalWeight;
    let grade = GRADES[GRADES.length - 1];
    for (const g of GRADES) {
        cursor -= g.weight;
        if (cursor <= 0) { grade = g; break; }
    }
    return {
        grade: grade.name,
        gradeColor: grade.color,
        text: pickBy(grade.texts, seed, 2),
        lane: pickBy(LUCKY_LANES, seed, 3),
        champ: pickBy(LUCKY_CHAMPS, seed, 4),
        number: 1 + Math.floor(roll(seed, 5) * 99),
        advice: pickBy(ADVICES, seed, 6),
    };
};

