/* --- 결정적 난수 (이름+날짜가 같으면 하루 종일 같은 운세) --- */

export const hashSeed = (s: string): number => {
    let h = 2166136261;
    for (let i = 0; i < s.length; i += 1) {
        h ^= s.charCodeAt(i);
        h = Math.imul(h, 16777619);
    }
    return h >>> 0;
};

const roll = (seed: number, salt: number): number =>
    (Math.imul(seed ^ (salt * 0x9e3779b9), 2654435761) >>> 0) / 4294967295;

const pickBy = <T,>(arr: T[], seed: number, salt: number): T =>
    arr[Math.floor(roll(seed, salt) * arr.length)];

